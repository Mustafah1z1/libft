#include "libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	unsigned char	*ss;
	unsigned char	cc;
	size_t			i;

	i = 0;
	cc = (unsigned char) c;
	ss = (unsigned char *) s;
	while (i < n)
	{
		if (ss[i] == cc)
			return ((void *) & ss[i]);
		i++;
	}
	return (NULL);
}
