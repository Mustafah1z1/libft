#include "libft.h"

char	*ft_strtrim(char const *s1, char const *set)
{
	char	*x;
	size_t	start;
	size_t	end;
	size_t	i;

	i = 0;
	start = 0;
	if (!s1 || !set)
		return (NULL);
	while (s1[start] != '\0' && ft_strchr(set, s1[start]) != NULL)
		start++;
	if (s1[start] == '\0')
		return (ft_strdup(""));
	end = ft_strlen(s1) - 1;
	while (end > start && ft_strchr(set, s1[end]) != NULL)
		end--;
	x = malloc(((end - start) + 2) * sizeof(char));
	if (!x)
		return (NULL);
	while (start <= end)
	{
		x[i] = s1[start];
		start++;
		i++;
	}
	x[i] = '\0';
	return (x);
}